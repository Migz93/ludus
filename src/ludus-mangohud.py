#!/usr/bin/env python3
"""Validated console HUD policy and private player configuration (no Steam writer)."""
from pathlib import Path
import os
import re
import time
import uuid

DEFAULT = {'enabled': False, 'font_size': 32, 'position': 'top-right',
           'fps': True, 'frametime': True, 'cpu_stats': True, 'cpu_temp': True,
           'gpu_stats': True, 'gpu_temp': True, 'ram': True, 'vram': True,
           'toggle_hud': 'Shift_R+F12'}
POSITIONS = ('top-left', 'top-right', 'top-center', 'middle-left', 'middle-right',
             'bottom-left', 'bottom-right', 'bottom-center')
# Deliberately bounded X11 key names, rather than arbitrary config text.
HOTKEY = re.compile(r'(?:(?:Shift_[LR]|Control_[LR]|Alt_[LR]|Super_[LR])\+)*(?:F(?:[1-9]|[12][0-9]|3[0-5])|[a-zA-Z0-9]|Home|End|Insert|Delete|Pause|Scroll_Lock)\Z')


def validate(policy, game=False):
    if not isinstance(policy, dict): raise ValueError('Invalid MangoHud policy')
    if game:
        if set(policy) - {'mode'} or policy.get('mode', 'inherit') not in ('inherit', 'enabled', 'disabled'):
            raise ValueError('MangoHud game policy must be inherit, enabled or disabled')
        return policy
    if set(policy) - set(DEFAULT): raise ValueError('Unknown MangoHud field')
    value = dict(DEFAULT, **policy)
    for key in set(DEFAULT) - {'font_size', 'position', 'toggle_hud'}:
        if type(value[key]) is not bool: raise ValueError(f'MangoHud {key} must be enabled or disabled')
    if type(value['font_size']) is not int or not 18 <= value['font_size'] <= 64:
        raise ValueError('MangoHud font size must be a whole number from 18 to 64')
    if value['position'] not in POSITIONS: raise ValueError('Unsupported MangoHud position')
    hotkey = value['toggle_hud']
    if not isinstance(hotkey, str) or len(hotkey) > 100 or not HOTKEY.fullmatch(hotkey):
        raise ValueError('Invalid HUD-toggle hotkey; use names such as Shift_R+F12')
    if len(hotkey.split('+')) != len(set(hotkey.split('+'))):
        raise ValueError('Duplicate HUD-toggle key')
    return policy


def layout(config):
    policy = dict(DEFAULT, **config['global'].get('mangohud', {}))
    validate(policy)
    return policy


def effective(config, appid):
    policy = layout(config)
    mode = config['games'].get(appid, {}).get('mangohud', {}).get('mode', 'inherit')
    on = policy['enabled'] if mode == 'inherit' else mode == 'enabled'
    return {key: value for key, value in policy.items() if key != 'enabled'} if on else None


def render(policy):
    validate(policy)
    return '# Generated by Ludus; configure through the management WebUI.\n' + ''.join(
        f'{key}={int(value) if type(value) is bool else value}\n'
        for key, value in dict(DEFAULT, **policy).items() if key != 'enabled')


def save(config, argument):
    scope = argument['scope']
    if scope == 'mangohud-reset':
        config['global'].pop('mangohud', None)
        for game in config['games'].values(): game.pop('mangohud', None)
    elif scope in ('mangohud-global', 'mangohud-game'):
        game = scope == 'mangohud-game'
        policy = dict(validate(argument.get('policy'), game))
        if game:
            appid = argument.get('appid')
            if not isinstance(appid, str) or not re.fullmatch(r'[0-9]+', appid): raise ValueError('Invalid app ID')
            config['games'].setdefault(appid, {})['mangohud'] = policy
        else: config['global']['mangohud'] = policy
    else: raise ValueError('Invalid MangoHud scope')


def config_path(home):
    return Path(home) / '.config/ludus/mangohud/MangoHud.conf'


def private_directory(home, relative):
    home = Path(home).resolve()
    current = home
    for part in Path(relative).parts:
        current /= part
        if current.is_symlink(): raise ValueError('Refusing symlink in MangoHud path')
        current.mkdir(mode=0o700, exist_ok=True)
        if not current.is_dir() or current.stat().st_uid != os.getuid():
            raise ValueError('MangoHud directories must belong to the player')
    current.chmod(0o700)
    return current


def prepare(home, policy, state, persist, io):
    """Capture audit backup before first enablement; never change the user's file."""
    path = config_path(home)
    private_directory(home, '.config/ludus/mangohud')
    if path.is_symlink(): raise ValueError('Refusing symlink MangoHud configuration')
    try:
        current = io.read_text(path)[0]
        if path.stat().st_uid != os.getuid(): raise ValueError('MangoHud config must belong to the player')
    except FileNotFoundError: current = None
    if state.get('pending') is not None and current == state['pending']:
        state['last'] = state['pending']
    if current is not None and current != state.get('last'):
        raise ValueError('Private Ludus MangoHud configuration changed outside Ludus; preserve it before retrying')
    if not state.get('backup_done'):
        user = Path(home) / '.config/MangoHud/MangoHud.conf'
        if user.resolve() != user: raise ValueError('Refusing symlink in user MangoHud configuration')
        try: original = io.read_text(user)[0]
        except FileNotFoundError: original = None
        if original is not None:
            backup_dir = private_directory(home, '.local/state/ludus/launch-options/mangohud-backups')
            backup = backup_dir / f'MangoHud-{time.time_ns()}-{uuid.uuid4().hex}.conf'
            io.atomic_text(backup, original)
            state['backup'] = str(backup)
        state['backup_done'] = True
        persist()
    desired = render(policy)
    # Journal before writing so interruption cannot strand an unrecognised file.
    state['pending'] = desired
    persist()
    if current != desired: io.atomic_text(path, desired)
    state.update(last=desired, status='applied')
    state.pop('pending', None)
    state.pop('error', None)
    persist()
    return str(path)


def cleanup(home, state, persist, io, referenced):
    if referenced or not state.get('last') and not state.get('pending'): return
    path = config_path(home)
    if path.resolve() != path: raise ValueError('Refusing symlink in MangoHud cleanup path')
    try: current = io.read_text(path)[0]
    except FileNotFoundError: current = None
    if current is not None and current not in (state.get('last'), state.get('pending')):
        raise ValueError('Private Ludus MangoHud configuration changed; cleanup skipped')
    if current is not None:
        path.unlink()
        fd = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY)
        try: os.fsync(fd)
        finally: os.close(fd)
    state.pop('last', None)
    state.pop('pending', None)
    state.pop('error', None)
    state['status'] = 'restored'
    persist()
